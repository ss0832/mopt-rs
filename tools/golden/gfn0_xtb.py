Z = {s: z + 1 for z, s in enumerate("H He Li Be B C N O F Ne Na Mg Al Si P S Cl Ar".split())}
Z.update({"Br": 35, "I": 53})


def main() -> None:
    import gfn0_rs

    calc = gfn0_rs.Gfn0NativeCalculator()
    cases = []
    for name, (symbols, ang, charge, mult) in MOLECULES.items():
        x = np.asarray(ang, dtype=float) * ANGSTROM
        numbers = [Z[s] for s in symbols]
        e = calc.energy(numbers, x, charge, mult)
        g = np.asarray(calc.gradient(numbers, x, charge, mult), dtype=float)
        cases.append(
            {
                "molecule": name,
                "symbols": symbols,
                "positions_bohr": x.ravel().tolist(),
                "charge": charge,
                "multiplicity": mult,
                "energy": e,
                "gradient": g.ravel().tolist(),
            }
        )
        print(name, e, file=sys.stderr)
    data = {
        "source": f"gfn0-rs {getattr(gfn0_rs, '__version__', '?')} Gfn0NativeCalculator",
        "python": platform.python_version(),
        "units": "positions Bohr, energy Hartree, gradient Hartree/Bohr",
        "cases": cases,
    }
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        json.dump(data, f, indent=1)


if __name__ == "__main__":
    main()
