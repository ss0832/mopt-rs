"""Generate reference ("golden") data by running the original MultiOptPy implementation.

Usage (inside the reference environment created by setup_ref_env.sh):

    python tools/golden/run_reference.py <multioptpy_root> <output_dir> [<work_dir> [<case> ...]]

With case names (``lj_ar7_adamlars`` ...), only those optimizations are run and the other files
are left as they are.

Two kinds of data are written as JSON (units: Bohr, Hartree):

* ``single_point_lj.json``: energy, gradient, and Hessian of MultiOptPy's Lennard-Jones
  calculator. (MultiOptPy's EMT and Tersoff calculators are wrong -- see
  ``docs/source/migration_surfaces.md`` -- so their reference values come from ASE, generated by
  ``ase_reference.py``.)
* ``opt_<case>.json``: full optimization trajectories of ``optmain`` on the LJ surface
  (structure, energy, and gradient at every iteration, plus the final result).

All input structures are centered at their centroid so that MultiOptPy's per-step Kabsch
re-centering does not shift the trajectory relative to mopt-rs (which centers the start).

This file is part of mopt-rs.
"""

import contextlib
import io
import json
import math
import os
import platform
import sys

import numpy as np


def centered(coords):
    c = np.asarray(coords, dtype=float)
    return c - c.mean(axis=0)


def pentagonal_bipyramid(symbol, a):
    r = a / (2.0 * math.sin(math.pi / 5.0))
    pos = []
    for k in range(5):
        t = k * 2.0 * math.pi / 5.0
        pos.append([r * math.cos(t) + 0.1 * math.sin(k), r * math.sin(t), 0.05 * k])
    pos += [[0.0, 0.0, 0.55 * a], [0.2, 0.0, -0.53 * a]]
    return [symbol] * 7, centered(pos)


STRUCTURES = {
    "ar7": pentagonal_bipyramid("Ar", 3.8),
    "cu7": pentagonal_bipyramid("Cu", 2.55),
    "si5": (
        ["Si"] * 5,
        centered(
            [[0.0, 0.0, 0.0], [2.3, 0.1, 0.0], [1.1, 2.0, 0.2], [1.2, 0.7, 1.9], [-0.9, 1.5, 1.4]]
        ),
    ),
    "cu_al4": (
        ["Cu", "Al", "Al", "Cu"],
        centered([[0.0, 0.0, 0.0], [2.6, 0.0, 0.0], [1.3, 2.2, 0.1], [1.2, 0.8, 2.1]]),
    ),
}

OPT_CASES = [
    # (name, calculator, structure, extra optmain arguments)
    ("lj_ar7_firelars", "lj", "ar7", []),
    ("lj_ar7_firelars_tcc", "lj", "ar7", ["-tcc"]),
    ("lj_ar7_rsirfo_bfgs", "lj", "ar7", ["-opt", "rsirfo_bfgs"]),
    ("lj_ar7_rsirfo_fsb", "lj", "ar7", ["-opt", "rsirfo_fsb"]),
    ("lj_ar7_rsirfo_bofill", "lj", "ar7", ["-opt", "rsirfo_bofill"]),
    ("lj_ar7_lbfgs", "lj", "ar7", ["-opt", "lbfgs"]),
    # First-order methods ported as they are (the first 30 iterations).
    ("lj_ar7_gradientdescent", "lj", "ar7", ["-opt", "gradientdescent", "-ns", "30"]),
    ("lj_ar7_mwgradientdescent", "lj", "ar7", ["-opt", "mwgradientdescent", "-ns", "30"]),
    ("lj_ar7_adamlars", "lj", "ar7", ["-opt", "adamlars", "-ns", "30"]),
    ("lj_ar7_radam", "lj", "ar7", ["-opt", "radam", "-ns", "30"]),
    ("lj_ar7_adabelief", "lj", "ar7", ["-opt", "adabelief", "-ns", "30"]),
    ("lj_ar7_eve", "lj", "ar7", ["-opt", "eve", "-ns", "30"]),
    ("lj_ar7_fire2", "lj", "ar7", ["-opt", "fire2", "-ns", "30"]),
    # Step modifiers ported as they are, on FIRE.
    ("lj_ar7_fire_locking", "lj", "ar7", ["-opt", "fire_coordinate_locking", "-ns", "30"]),
    ("lj_ar7_fire_scaling", "lj", "ar7", ["-opt", "fire_component_wise_scaling", "-ns", "30"]),
]

SINGLE_POINTS = {"lj": ["ar7"]}

ANG2BOHR = 1.0 / 0.52917721067


def write_xyz(path, symbols, coords_ang):
    with open(path, "w") as f:
        f.write(f"{len(symbols)}\n0 1\n")
        for s, (x, y, z) in zip(symbols, coords_ang, strict=True):
            f.write(f"{s} {x:.12f} {y:.12f} {z:.12f}\n")


def versions():
    import scipy
    import torch

    return {
        "python": platform.python_version(),
        "numpy": np.__version__,
        "scipy": scipy.__version__,
        "torch": torch.__version__,
        "multioptpy": "1.21.2",
    }


def single_points(out_dir):
    from multioptpy.Calculator.lj_calculation_tools import LennardJonesCore

    cores = {"lj": LennardJonesCore}
    for calc, names in SINGLE_POINTS.items():
        records = []
        for name in names:
            symbols, coords = STRUCTURES[name]
            core = cores[calc]()
            bohr = coords * ANG2BOHR
            with contextlib.redirect_stdout(io.StringIO()):
                eg = core.calculate_energy_and_gradient(bohr.copy(), symbols)
                h = core.calculate_hessian(bohr.copy(), symbols)
            records.append(
                {
                    "structure": name,
                    "symbols": symbols,
                    "coords_bohr": bohr.tolist(),
                    "energy_hartree": float(eg["energy"]),
                    "gradient": np.asarray(eg["gradient"]).reshape(-1).tolist(),
                    "hessian": np.asarray(h["hessian"]).tolist(),
                }
            )
        dump(
            out_dir,
            f"single_point_{calc}.json",
            {"meta": versions(), "calculator": calc, "points": records},
        )


def dump(out_dir, name, data):
    path = os.path.join(out_dir, name)
    with open(path, "w") as f:
        json.dump(data, f, indent=1)
    print("wrote", path, file=sys.stderr)


def optimization(out_dir, work_dir, name, calc, structure, extra):
    import multioptpy.interface as interface
    import multioptpy.optimization as optimization

    symbols, coords = STRUCTURES[structure]
    case_dir = os.path.join(work_dir, name)
    os.makedirs(case_dir, exist_ok=True)
    xyz = os.path.join(case_dir, f"{name}.xyz")
    write_xyz(xyz, symbols, coords)

    frames = []
    original = optimization.StandardHandler.compute

    def recording_compute(self, state):
        state = original(self, state)
        frames.append(
            {
                "coords_bohr": np.asarray(state.geometry, dtype=float).reshape(-1).tolist(),
                "energy_hartree": float(state.raw_energy),
                "gradient": np.asarray(state.raw_gradient, dtype=float).reshape(-1).tolist(),
            }
        )
        return state

    argv = ["optmain", xyz, "-os", calc, "-nosymm"] + extra
    optimization.StandardHandler.compute = recording_compute
    old_argv, old_cwd = sys.argv, os.getcwd()
    try:
        sys.argv = argv
        os.chdir(case_dir)
        parser = interface.init_parser()
        args = interface.optimizeparser(parser)
        with contextlib.redirect_stdout(io.StringIO()):
            job = optimization.Optimize(args)
            job.run()
    finally:
        optimization.StandardHandler.compute = original
        sys.argv = old_argv
        os.chdir(old_cwd)

    dump(
        out_dir,
        f"opt_{name}.json",
        {
            "meta": versions(),
            "calculator": calc,
            "structure": structure,
            "symbols": symbols,
            "arguments": argv[2:],
            "initial_coords_bohr": (coords * ANG2BOHR).reshape(-1).tolist(),
            "converged": bool(job.optimized_flag),
            "iterations": len(frames),
            "final_energy_hartree": float(job.final_energy),
            "frames": frames,
        },
    )


def main():
    root, out_dir = sys.argv[1], sys.argv[2]
    work_dir = sys.argv[3] if len(sys.argv) > 3 else os.path.expanduser("~/.cache/mopt-golden-work")
    os.makedirs(out_dir, exist_ok=True)
    os.makedirs(work_dir, exist_ok=True)
    os.environ.setdefault("MPLBACKEND", "Agg")
    sys.path.insert(0, root)
    only = sys.argv[4:]
    unknown = set(only) - {case[0] for case in OPT_CASES}
    if unknown:
        raise SystemExit(f"unknown cases: {sorted(unknown)}")
    if not only:
        single_points(out_dir)
    for case in OPT_CASES:
        if not only or case[0] in only:
            optimization(out_dir, work_dir, *case)


if __name__ == "__main__":
    main()
