import collections
import json
import sys
from pathlib import Path


def main() -> None:
    root = Path(sys.argv[1])
    items = json.loads((root / "tests/coverage/multioptpy_inventory.json").read_text())["items"]
    entries = json.loads((root / "tools/coverage/mapping.json").read_text())["entries"]

    def entry(item_id: str) -> str:
        best = ""
        for k in entries:
            if item_id.startswith(k) and len(k) > len(best):
                best = k
        return best

    per_entry: dict[str, int] = collections.Counter()
    totals: dict[str, int] = collections.Counter()
    for it in items:
        k = entry(it["id"])
        per_entry[k] += 1
        e = entries[k]
        totals[e["status"]] += 1
    lines = [
        "# MultiOptPy feature coverage",
        "",
        "Every module, class, function, method, and command-line option of MultiOptPy 1.21.2",
        "(`tests/coverage/multioptpy_inventory.json`, made by `tools/coverage/inventory.py`) is",
        "mapped to mopt-rs in `tools/coverage/mapping.json`; `tests/test_coverage.py` fails for",
        "unmapped items. Items not implemented yet are listed, and are no condition of a release.",
        "This page is generated by `tools/coverage/report.py`.",
        "",
        f"Items: {len(items)}; implemented: {totals['done']}; not implemented yet: "
        f"{totals['pending']}; not provided by decision: {totals['dropped']}",
        "",
        "| MultiOptPy | items | status | mopt-rs |",
        "|---|---|---|---|",
    ]
    for k in sorted(entries):
        if per_entry.get(k, 0) == 0:
            continue
        e = entries[k]
        status = {"done": "implemented", "dropped": "not provided"}.get(
            e["status"], "not implemented yet"
        )
        lines.append(f"| `{k}` | {per_entry[k]} | {status} | {e['where']} |")
    out = root / "docs/source/coverage.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
