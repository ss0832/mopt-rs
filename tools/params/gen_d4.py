"""Generate the DFT-D4 and EEQ-2019 tables of mopt-rs from dftd4 and multicharge sources.

Inputs (dftd4/dftd4 and grimme-lab/multicharge, LGPL-3.0-or-later): ``src/dftd4/reference.inc``,
``src/dftd4/data/{hardness,zeff,en,r4r2}.f90`` and
``src/multicharge/param/eeq2019.f90``. Output: ``crates/mopt-rs/src/parameters/d4_reference.rs``.

Usage:
    python -I tools/params/gen_d4.py <dir with the downloaded files> <repository root>

The directory must contain ``reference.inc``, ``data_hardness.f90``, ``data_zeff.f90``,
``data_en.f90``, ``data_r4r2.f90``, and ``mc_param_eeq2019.f90``.

This file is part of mopt-rs.
Copyright (C) 2023-2026 ss0832
SPDX-License-Identifier: GPL-3.0-or-later
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

MAX_ELEM = 118
MAX_REF = 7
NFREQ = 23
NSEC = 17
NUM = re.compile(r"[-+]?\d+\.\d*(?:[eEdD][-+]?\d+)?(?:_wp)?|[-+]?\d+(?=\s*[,\]&/])")


def numbers(text: str) -> list[float]:
    out = []
    for m in NUM.finditer(text):
        s = m.group(0).replace("_wp", "").replace("d", "e").replace("D", "e")
        out.append(float(s))
    return out


def strip_comments(src: str) -> str:
    return "\n".join(line.split("!")[0] for line in src.splitlines())


def parameter_array(path: Path, name: str, size: int) -> list[float]:
    src = strip_comments(path.read_text(encoding="utf-8"))
    m = re.search(rf"{name}\s*\(\s*max_elem\s*\)\s*=\s*\[(.*?)\]", src, re.S)
    if m is None:
        raise SystemExit(f"{path}: {name} not found")
    vals = numbers(m.group(1) + "]")
    if len(vals) != size:
        raise SystemExit(f"{path}: {name} has {len(vals)} values, expected {size}")
    return vals


def parse_reference(path: Path) -> dict[str, dict[tuple[int, ...], list[float]]]:
    src = strip_comments(path.read_text(encoding="utf-8"))
    data: dict[str, dict[tuple[int, ...], list[float]]] = {}
    for m in re.finditer(r"data\s+(\w+)\s*\(([^)]*)\)\s*/(.*?)/", src, re.S):
        name = m.group(1).lower()
        idx = tuple(int(t) for t in m.group(2).replace(" ", "").split(",") if t not in (":", ""))
        vals = numbers(m.group(3).replace("&", " ") + " /")
        data.setdefault(name, {})[idx] = vals
    return data


def fmt(v: float) -> str:
    s = repr(float(v))
    return s if ("." in s or "e" in s or "inf" in s) else s + ".0"


def table2(name: str, doc: str, rows: list[list[float]], ty: str = "f64") -> list[str]:
    n = len(rows[0])
    out = [f"/// {doc}", f"pub static {name}: [[{ty}; {n}]; {len(rows)}] = ["]
    conv = (lambda v: str(int(v))) if ty != "f64" else fmt
    out += [f"    [{', '.join(conv(v) for v in row)}]," for row in rows]
    out.append("];")
    return out


def main() -> None:
    src, root = Path(sys.argv[1]), Path(sys.argv[2])
    ref = parse_reference(src / "reference.inc")
    nref = [int(ref["refn"].get((z,), [0])[0]) for z in range(1, MAX_ELEM + 1)]

    def per_ref(name: str) -> list[list[float]]:
        rows = []
        for z in range(1, MAX_ELEM + 1):
            row = [0.0] * MAX_REF
            for r in range(1, nref[z - 1] + 1):
                # Entries absent from reference.inc are zero in dftd4's static arrays.
                v = ref[name].get((r, z), [0.0])
                row[r - 1] = v[0]
            rows.append(row)
        return rows

    alpha = []
    for z in range(1, MAX_ELEM + 1):
        for r in range(1, MAX_REF + 1):
            v = ref["alphaiw"].get((r, z)) if r <= nref[z - 1] else None
            alpha.append(v if v is not None else [0.0] * NFREQ)
            if v is not None and len(v) != NFREQ:
                raise SystemExit(f"alphaiw({r},{z}) has {len(v)} values")
    sscale = [ref["sscale"].get((s,), [0.0])[0] for s in range(1, NSEC + 1)]
    secaiw = [ref["secaiw"].get((s,), [0.0] * NFREQ) for s in range(1, NSEC + 1)]
    hard = parameter_array(src / "data_hardness.f90", "chemical_hardness", MAX_ELEM)
    zeff = parameter_array(src / "data_zeff.f90", "effective_nuclear_charge", MAX_ELEM)
    en = parameter_array(src / "data_en.f90", "pauling_en", MAX_ELEM)
    r4r2 = parameter_array(src / "data_r4r2.f90", "r4_over_r2", MAX_ELEM)
    eeq = src / "mc_param_eeq2019.f90"
    chi = parameter_array(eeq, "eeq_chi", 103)
    eta = parameter_array(eeq, "eeq_eta", 103)
    kcn = parameter_array(eeq, "eeq_kcnchi", 103)
    rad = parameter_array(eeq, "eeq_rad", 103)

    out = [
        "//! DFT-D4 and EEQ-2019 reference data generated by `tools/params/gen_d4.py` from dftd4",
        "//! (`src/dftd4/reference.inc`, `src/dftd4/data/*.f90`) and multicharge",
        "//! (`src/multicharge/param/eeq2019.f90`), LGPL-3.0-or-later (E. Caldeweyher et al.,",
        "//! J. Chem. Phys. 2019, 150, 154122). Do not edit by hand.",
        "//!",
        "//! MultiOptPy: no counterpart (new in mopt-rs); MultiOptPy's own `Parameters/d4.py` is in",
        "//!  `multioptpy_tables`.",
        "//!",
        "//! This file is part of mopt-rs.",
        "//! Copyright (C) 2023-2026 ss0832",
        "//! SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        "/// Number of reference systems per element (`Z = 1..=118`; 0: no data).",
        f"pub static D4_NREF: [u8; {MAX_ELEM}] = [{', '.join(str(n) for n in nref)}];",
        "",
    ]
    out += table2(
        "D4_REF_COVCN",
        "Covalent coordination numbers of the reference systems.",
        per_ref("refcovcn"),
    )
    out += [""] + table2(
        "D4_REF_CN",
        "Coordination numbers deciding the number of Gaussian weights.",
        per_ref("refcn"),
    )
    out += [""] + table2("D4_REF_Q", "EEQ charges of the reference systems.", per_ref("clsq"))
    out += [""] + table2(
        "D4_REF_H", "EEQ charges of the hydrogen-like secondary systems.", per_ref("clsh")
    )
    out += [""] + table2(
        "D4_HCOUNT", "Number of secondary systems per reference.", per_ref("hcount")
    )
    out += [""] + table2(
        "D4_ASCALE", "Scaling of the reference polarizabilities.", per_ref("ascale")
    )
    out += [""] + table2(
        "D4_REFSYS", "Secondary system (atomic number) per reference.", per_ref("refsys"), "u8"
    )
    out += [
        "",
        "/// Dynamic polarizabilities of the reference systems at the 23 imaginary frequencies,",
        "/// indexed `[7 (Z - 1) + ref]`.",
        f"pub static D4_ALPHAIW: [[f64; {NFREQ}]; {len(alpha)}] = [",
    ]
    out += [f"    [{', '.join(fmt(v) for v in row)}]," for row in alpha]
    out += [
        "];",
        "",
        "/// Scaling of the secondary systems.",
        f"pub static D4_SSCALE: [f64; {NSEC}] = [{', '.join(fmt(v) for v in sscale)}];",
        "",
    ]
    out += table2("D4_SECAIW", "Polarizabilities of the secondary systems.", secaiw)
    for name, doc, vals in [
        ("D4_HARDNESS", "Chemical hardnesses of the charge scaling.", hard),
        ("D4_ZEFF", "Effective nuclear charges.", zeff),
        ("D4_PAULING_EN", "Pauling electronegativities of the covalent coordination number.", en),
        ("D4_R4_OVER_R2", "`<r^4> / <r^2>` atomic expectation values.", r4r2),
        ("EEQ_CHI", "EEQ-2019 electronegativities (`Z = 1..=103`).", chi),
        ("EEQ_ETA", "EEQ-2019 chemical hardnesses.", eta),
        ("EEQ_KCNCHI", "EEQ-2019 coordination-number scaling of the electronegativity.", kcn),
        ("EEQ_RAD", "EEQ-2019 charge widths (Bohr).", rad),
    ]:
        out += [
            "",
            f"/// {doc}",
            f"pub static {name}: [f64; {len(vals)}] = [{', '.join(fmt(v) for v in vals)}];",
        ]
    dst = root / "crates/mopt-rs/src/parameters/d4_reference.rs"
    dst.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {dst}: {sum(nref)} reference systems")


if __name__ == "__main__":
    main()
