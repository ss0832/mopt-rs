"""Generate the most-abundant-isotope masses used by MultiOptPy (NIST values, Z = 1..86).

Usage:

    python -I tools/params/gen_isotope_masses.py <MultiOptPy root> <output .rs>

The table is read from ``multioptpy/Parameters/atomic_mass.py`` with ``ast`` (not executed).

This file is part of mopt-rs.
"""

import ast
import sys
from pathlib import Path


def main() -> None:
    root, out = Path(sys.argv[1]), Path(sys.argv[2])
    tree = ast.parse((root / "multioptpy/Parameters/atomic_mass.py").read_text(encoding="utf-8"))
    table = None
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "mass" for t in node.targets
        ):
            table = ast.literal_eval(node.value)
    if not isinstance(table, dict):
        raise SystemExit("mass table not found")
    zmax = max(table)
    values = [table.get(z, 0.0) for z in range(zmax + 1)]
    lines = [
        "//! Masses of the most abundant isotopes (u), Z = 1..=86 (NIST, Atomic Weights and Isotopic",
        "//! Compositions); index 0 is unused. MultiOptPy uses these where mopt-rs otherwise uses",
        "//! standard atomic weights, so its model Hessians (`legacy_`) need them.",
        "//!",
        "//! Generated by tools/params/gen_isotope_masses.py; do not edit.",
        "//!",
        "//! MultiOptPy: `Parameters/atomic_mass.py:atomic_mass`.",
        "//!",
        "//! This file is part of mopt-rs.",
        "//! Copyright (C) 2023-2026 ss0832",
        "//! SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        f"/// Most abundant isotope masses (u) by atomic number (0..={zmax}).",
        f"pub static MOST_ABUNDANT_ISOTOPE_MASS_U: [f64; {zmax + 1}] = [",
    ]
    lines += [f"    {v!r}," for v in values]
    lines.append("];")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out} ({zmax} elements)")


if __name__ == "__main__":
    main()
