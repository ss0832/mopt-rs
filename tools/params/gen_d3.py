"""Generate the DFT-D3 reference tables of mopt-rs from simple-dftd3's Fortran sources.

Inputs: ``reference.f90`` and ``data/r4r2.f90`` of simple-dftd3 (https://github.com/dftd3/
simple-dftd3, LGPL-3.0-or-later). Output: ``crates/mopt-rs/src/parameters/d3_reference.rs``
with the number of reference systems, their coordination numbers, the r4/r2 expectation values,
and the reference C6 coefficients of every element pair (only the populated reference blocks,
in the order ``(Z_a >= Z_b, ref_a, ref_b)``).

Usage:
    python -I tools/params/gen_d3.py <reference.f90> <r4r2.f90> <repository root>

This file is part of mopt-rs.
Copyright (C) 2023-2026 ss0832
SPDX-License-Identifier: GPL-3.0-or-later
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

MAX_ELEM = 103
MAX_REF = 7
NUM = re.compile(r"[-+]?\d+\.\d*(?:[eEdD][-+]?\d+)?_wp|[-+]?\d+(?=\s*[,\]&])")


def numbers(text: str) -> list[float]:
    return [
        float(m.group(0).replace("_wp", "").replace("d", "e").replace("D", "e"))
        for m in NUM.finditer(text)
    ]


def block(src: str, start: str, end: str) -> str:
    i = src.index(start)
    j = src.index(end, i)
    return src[i + len(start) : j]


def strip_comments(src: str) -> str:
    return "\n".join(line.split("!")[0] for line in src.splitlines())


def parse_reference(path: Path) -> tuple[list[int], list[list[float]], list[float]]:
    raw = path.read_text(encoding="utf-8")
    src = strip_comments(raw)
    nref = [int(v) for v in numbers(block(src, "number_of_references(max_elem) = [", "]") + "]")]
    cn = numbers(block(src, "reference_cn(max_ref, max_elem) = reshape([", "]"))
    if len(nref) != MAX_ELEM or len(cn) != MAX_REF * MAX_ELEM:
        raise SystemExit(f"unexpected sizes: {len(nref)} references, {len(cn)} CNs")
    ref_cn = [cn[MAX_REF * e : MAX_REF * (e + 1)] for e in range(MAX_ELEM)]
    npair = MAX_ELEM * (MAX_ELEM + 1) // 2
    flat = [0.0] * (MAX_REF * MAX_REF * npair)
    for m in re.finditer(r"c6ab_view\((\d+):(\d+)\)\s*=\s*\[(.*?)\]", src, re.S):
        lo, hi = int(m.group(1)), int(m.group(2))
        vals = numbers(m.group(3))
        if len(vals) != hi - lo + 1:
            raise SystemExit(f"block {lo}:{hi} has {len(vals)} values")
        flat[lo - 1 : hi] = vals
    return nref, ref_cn, flat


def parse_r4r2(path: Path) -> list[float]:
    src = strip_comments(path.read_text(encoding="utf-8"))
    vals = numbers(block(src, "r4_over_r2(max_elem) = [", "]"))
    if len(vals) != 118:
        raise SystemExit(f"r4/r2 has {len(vals)} values")
    return vals


def fmt(v: float) -> str:
    s = repr(float(v))
    return s if ("." in s or "e" in s) else s + ".0"


def main() -> None:
    ref_path, r4r2_path, root = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    nref, ref_cn, flat = parse_reference(ref_path)
    r4r2 = parse_r4r2(r4r2_path)
    offsets: list[int] = []
    c6: list[float] = []
    for a in range(1, MAX_ELEM + 1):
        for b in range(1, a + 1):
            ic = b + a * (a - 1) // 2
            offsets.append(len(c6))
            for ia in range(nref[a - 1]):
                for ib in range(nref[b - 1]):
                    c6.append(flat[ia + MAX_REF * ib + MAX_REF * MAX_REF * (ic - 1)])
    out = [
        "//! DFT-D3 reference data generated by `tools/params/gen_d3.py` from simple-dftd3",
        "//! (`src/dftd3/reference.f90`, `src/dftd3/data/r4r2.f90`; S. Grimme, J. Antony, S. Ehrlich,",
        "//! H. Krieg, J. Chem. Phys. 2010, 132, 154104; LGPL-3.0-or-later). Do not edit by hand.",
        "//!",
        "//! MultiOptPy: no counterpart (new in mopt-rs); MultiOptPy's own `Parameters/d3.py` is in",
        "//!  `multioptpy_tables`.",
        "//!",
        "//! This file is part of mopt-rs.",
        "//! Copyright (C) 2023-2026 ss0832",
        "//! SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        "/// Number of elements with reference data (`Z = 1..=103`).",
        f"pub const D3_MAX_ELEM: usize = {MAX_ELEM};",
        "",
        "/// Number of reference systems per element.",
        f"pub static D3_NREF: [u8; {MAX_ELEM}] = [{', '.join(str(n) for n in nref)}];",
        "",
        "/// Coordination numbers of the reference systems (unused slots are -1).",
        f"pub static D3_REF_CN: [[f64; {MAX_REF}]; {MAX_ELEM}] = [",
    ]
    out += [f"    [{', '.join(fmt(v) for v in row)}]," for row in ref_cn]
    out += [
        "];",
        "",
        "/// `<r^4> / <r^2>` atomic expectation values (`Z = 1..=118`).",
        f"pub static D3_R4_OVER_R2: [f64; 118] = [{', '.join(fmt(v) for v in r4r2)}];",
        "",
        "/// Offset into [`D3_C6`] of the pair `(Z_a >= Z_b)`, index `Z_b - 1 + Z_a (Z_a - 1) / 2`.",
        f"pub static D3_C6_OFFSET: [u32; {len(offsets)}] = [{', '.join(str(o) for o in offsets)}];",
        "",
        "/// Reference C6 coefficients (atomic units), `nref(Z_a) x nref(Z_b)` per pair, row-major.",
        f"pub static D3_C6: [f64; {len(c6)}] = [",
    ]
    for i in range(0, len(c6), 8):
        out.append("    " + ", ".join(fmt(v) for v in c6[i : i + 8]) + ",")
    out.append("];")
    dst = root / "crates/mopt-rs/src/parameters/d3_reference.rs"
    dst.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {dst}: {len(c6)} C6 values")


if __name__ == "__main__":
    main()
