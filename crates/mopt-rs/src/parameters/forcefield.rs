/// UFF van der Waals equilibrium distance in Bohr.
#[inline]
pub fn uff_vdw_distance_bohr(el: Element) -> f64 {
    UFF_VDW_DIST_ANG[clamp_z86(el)] * Units::ANGSTROM_TO_BOHR
}

/// UFF van der Waals well depth in Hartree.
#[inline]
pub fn uff_vdw_well_depth_hartree(el: Element) -> f64 {
    UFF_VDW_DEPTH_KCAL[clamp_z86(el)] * Units::KCAL_MOL_TO_HARTREE
}

/// UFF effective atomic charge `Z*`.
#[inline]
pub fn uff_effective_charge(el: Element) -> f64 {
    UFF_EFF_CHARGE[clamp_z86(el)]
}

/// DREIDING van der Waals distance in Bohr.
#[inline]
pub fn dreiding_vdw_distance_bohr(el: Element) -> f64 {
    DREIDING_VDW_DIST_ANG[clamp_z86(el)] * Units::ANGSTROM_TO_BOHR
}

/// DREIDING van der Waals well depth in Hartree.
#[inline]
pub fn dreiding_vdw_well_depth_hartree(el: Element) -> f64 {
    DREIDING_VDW_DEPTH_KCAL[clamp_z86(el)] * Units::KCAL_MOL_TO_HARTREE
}

/// GNB softness `s` in Bohr.
#[inline]
pub fn gnb_s_bohr(el: Element) -> f64 {
    GNB_S_ANG[clamp_z86(el)] * Units::ANGSTROM_TO_BOHR
}

/// GNB damping parameter `beta` in Bohr.
#[inline]
pub fn gnb_beta_bohr(el: Element) -> f64 {
    GNB_BETA_ANG[clamp_z86(el)] * Units::ANGSTROM_TO_BOHR
}

/// GNB core radius in Bohr.
#[inline]
pub fn gnb_radius_bohr(el: Element) -> f64 {
    GNB_RADII_ANG[clamp_z86(el)] * Units::ANGSTROM_TO_BOHR
}

/// GNB `C_6` dispersion coefficient in `Hartree * Bohr^6`.
#[inline]
pub fn gnb_c6_au(el: Element) -> f64 {
    let b2a = Units::BOHR_TO_ANGSTROM;
    let b2a6 = b2a * b2a * b2a * b2a * b2a * b2a;
    GNB_C6_KCAL_ANG6[clamp_z86(el)] * Units::KCAL_MOL_TO_HARTREE / b2a6
}

/// GNB effective van der Waals distance in Bohr.
#[inline]
pub fn gnb_vdw_distance_bohr(el: Element) -> f64 {
    GNB_VDW_DIST_ANG[clamp_z86(el)] * Units::ANGSTROM_TO_BOHR
}

/// GNB effective van der Waals well depth in Hartree.
#[inline]
pub fn gnb_vdw_well_depth_hartree(el: Element) -> f64 {
    GNB_VDW_DEPTH_KCAL[clamp_z86(el)] * Units::KCAL_MOL_TO_HARTREE
}
