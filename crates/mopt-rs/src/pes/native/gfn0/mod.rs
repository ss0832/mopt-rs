    /// The analytic Hessian against central differences of the analytic gradient.
    fn check_hessian(sys: &MolecularSystem) {
        check_hessian_with_step(sys, 5.0e-4);
    }

    /// As [`check_hessian`], with the step of the differences (their error grows as its
    /// square).
    fn check_hessian_with_step(sys: &MolecularSystem, step: f64) {
        let calc = Gfn0Xtb {
            hessian_step_bohr: step,
            ..Gfn0Xtb::default()
        };
        let analytic = calc.analytic_hessian(sys).unwrap();
        let numerical = calc.numerical_hessian_of(sys, 0).unwrap();
        let dim = analytic.nrows();
        let mut worst = (0.0_f64, 0, 0);
        for i in 0..dim {
            for j in 0..dim {
                let d = (analytic[(i, j)] - numerical[(i, j)]).abs();
                if d > worst.0 {
                    worst = (d, i, j);
                }
            }
        }
        let (d, i, j) = worst;
        assert!(
            d < 2.0e-6,
            "max |analytic - differences| = {d:.3e} at ({i}, {j}): {} vs {}",
            analytic[(i, j)],
            numerical[(i, j)]
        );
    }

