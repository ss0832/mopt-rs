//! GFN0-xTB (P. Pracht, E. Caldeweyher, S. Ehlert, S. Grimme, "A Robust Non-Self-Consistent
//! Tight-Binding Quantum Chemistry Method for large Molecules", ChemRxiv 2019,
//! DOI 10.26434/chemrxiv.8326202.v1) for H to Rn, built into mopt-rs.
//!
//! Provenance: the method follows gfn0-rs (github.com/ss0832/gfn0-rs, GPL-3.0-or-later, by the
//! author of mopt-rs), which reproduces the official xtb implementation (grimme-lab/xtb,
//! LGPL-3.0-or-later); the fitted parameters are xtb's `param_gfn0-xtb.txt`, the SRB data xtb's
//! `approxrab.f90`, and the D4 charges multicharge's EEQ-2019 parameters, all generated by
//! `tools/params/gen_gfn0_xtb.py` into [`crate::parameters::gfn0_xtb`]; the D4 reference data
//! are those of mopt-rs's DFT-D4 ([`crate::pes::dispersion::d4`]). gfn0-rs's extensions (the
//! NN parameter field, multipole, exchange, and ACP corrections, periodic systems) are not
//! included. Other elements are refused.
//!
//! Energy terms: the electronic free energy of H0 at 300 K, EEQ electrostatics, repulsion, the
//! short-range basis correction, and D4 dispersion. The gradient and the Hessian of the ground
//! state are analytic (module `hessian`; central differences of the gradient on request, and
//! for excited states).
//!
//! Excited singlet states (`EvalRequest::excited_state > 0`) are an addition of mopt-rs, not
//! part of GFN0-xTB: a simplified Tamm-Dancoff approximation on the GFN0-xTB orbitals, with
//! gradients by differences that follow the states (module `excited`).
//!
//! MultiOptPy: no counterpart (new in mopt-rs; MultiOptPy's GFN0-like model Hessian is
//! `model_hessian::legacy::gfn0xtb`).
//!
